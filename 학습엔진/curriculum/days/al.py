# -*- coding: utf-8 -*-
"""Algorithm (al) 7-day plan builder across code/analysis/proof/sketch/write modes."""
from curriculum.common import day, day_title, particle_eul, with_focus


def algo_days(prev, title, claim, trace, code, trap, cost, check, practice="code", prev_line="", prev_practice=None):
    past_mode = prev_practice or practice
    if prev == "시작":
        opening = with_focus(
            f"오늘은 '{title}'{particle_eul(title)} 코드 없이 시작한다. 다음 예를 손으로 한 줄씩 따라가고, 각 줄의 결과만 적는다.",
            trace,
        )
    elif past_mode in ("proof", "write", "analysis", "sketch"):
        opening = with_focus(
            f"지난주 '{prev}'의 가정과 결론을 코드 없이 말한다. 그 내용은 다음이다.",
            prev_line,
        )
    else:
        opening = with_focus(
            f"지난주 '{prev}'의 다음 예를 코드 없이 다시 따라간다.",
            prev_line,
        )
    draft_cue = trace if code.endswith("같은 절차로 처리한다.") else code
    if practice == "sketch":
        return [
            day(day_title(title, "진술"), [
                (10, opening),
                (20, claim + " 정리·개념의 가정과 결론을 적고, 이번 주에 증명하지 않고 남길 범위를 표시한다."),
                (20, "가정이 빠졌을 때 성립하지 않는 경우를 작은 입력으로 확인한다."),
                (10, "주장과 적용 경계를 한 문장으로 줄인다."),
            ]),
            day(day_title(title, "의미"), [
                (10, with_focus(f"어제 줄인 '{title}' 주장과 경계를 말한다.", claim)),
                (25, trace + " 진술이 보장하는 것과 보장하지 않는 것을 표로 나눈다."),
                (15, "입력을 하나 바꿔 같은 경계를 확인한다."),
                (10, "경계가 어긋나는 점을 표시한다."),
            ]),
            day(day_title(title, "스케치"), [
                (10, with_focus(f"어제 '{title}'에서 확인한 예를 말한다.", trace)),
                (40, "오늘 진술·가정·스케치 노트를 쓴다. " + draft_cue + " 첫 25분은 가정, 핵심 아이디어 골격, 생략한 증명 경계를 적되 전체 상수·일반 증명을 완성했다고 쓰지 않는다. 이 문장을 코드로 실행하지 않는다. 남은 15분은 작은 숫자로 가정이 맞는지 대조한다. 해설은 25분이 지나기 전에는 열지 않는다."),
                (10, "진술과 한계가 예 숫자와 맞는지 한 줄로 말한다."),
            ]),
            day(day_title(title, "반례"), [
                (10, with_focus(f"어제 '{title}' 스케치의 핵심 한계를 말한다. 예는 다음이다.", trace)),
                (20, trap),
                (20, "가정이 깨지는 입력을 만들고, 진술의 어느 조건이 무너지는지 적는다."),
                (10, "무엇을 고쳤는지 한 줄로 적는다."),
            ]),
            day(day_title(title, "경계"), [
                (10, with_focus(f"어제 '{title}'에서 고친 경계를 말한다. 그 실패는 다음이다.", trap)),
                (20, cost),
                (20, "그 경계를 예 숫자에 대입해 세 줄로 확인한다."),
                (10, "적용 한계를 한 문장으로 말한다."),
            ]),
            day(day_title(title, "설명"), [
                (10, with_focus(f"어제 적은 '{title}'의 적용 한계를 말한다.", cost)),
                (20, "노트를 가리고 가정, 진술, 생략한 경계를 다시 쓴다."),
                (20, "왜 이 조건에서만 호출할 수 있는지 세 문장으로 적는다."),
                (10, "세 문장을 소리 내어 말한다."),
            ]),
            day(day_title(title, "점검"), [
                (10, with_focus(f"이번 주 '{title}' 진술을 말한다.", claim)),
                (40, check + " 백지에서 진술·가정·경계를 다시 쓰고 생략한 증명 범위를 구분한다. 코드를 새로 짜거나 진술을 증명 완료로 적지 않는다."),
                (10, "막힌 줄을 다음 주 첫날 맨 위에 적는다. 오늘은 새 정리를 열지 않는다."),
            ]),
        ]
    if practice == "write":
        return [
            day(day_title(title, "범위"), [
                (10, opening),
                (20, claim),
                (20, "이번 주가 다루는 질문·독자·하지 않을 것을 세 줄로 고정한다."),
                (10, "범위를 한 문장으로 줄인다."),
            ]),
            day(day_title(title, "골격"), [
                (10, with_focus(f"어제 줄인 '{title}' 범위를 말한다.", claim)),
                (25, trace + " 가정·핵심·결론 또는 목차 뼈대를 적는다."),
                (15, "뼈대에 예 숫자나 인용할 정리를 옆에 붙인다."),
                (10, "뼈대가 범위를 넘으면 줄을 지운다."),
            ]),
            day(day_title(title, "초고"), [
                (10, with_focus(f"어제 '{title}' 뼈대를 말한다.", trace)),
                (40, "오늘 초고를 쓴다. " + draft_cue + " 첫 25분은 본문만 쓰고 코드를 새로 짜지 않는다. 남은 15분은 빈칸과 중복을 표시한다."),
                (10, "초고 제목과 분량을 한 줄로 적는다."),
            ]),
            day(day_title(title, "한계"), [
                (10, with_focus(f"어제 '{title}' 초고 제목을 말한다.", trace)),
                (20, trap),
                (20, "증명하지 않은 줄·가정 밖 사례·열린 질문을 한계 절로 옮긴다."),
                (10, "한계 세 줄을 남긴다."),
            ]),
            day(day_title(title, "퇴고"), [
                (10, with_focus(f"어제 '{title}' 한계 세 줄을 말한다.", trap)),
                (20, cost),
                (20, "중복 문장을 지우고 진술 상자와 예 하나를 본문에 고정한다."),
                (10, "퇴고 기준을 한 문장으로 말한다."),
            ]),
            day(day_title(title, "설명"), [
                (10, with_focus(f"어제 적은 '{title}' 퇴고 기준을 말한다.", cost)),
                (20, "노트를 덮고 질문·결론·예·한계를 백지에 다시 쓴다."),
                (20, "10분 설명 스크립트를 세 문장으로 줄여 소리 내어 말한다."),
                (10, "막힌 문장만 표시한다."),
            ]),
            day(day_title(title, "점검"), [
                (10, with_focus(f"이번 주 '{title}' 범위를 말한다.", claim)),
                (40, check + " 백지에서 첫 쪽 요약과 한계를 다시 쓰고, 코드 실행으로 이 칸을 대신하지 않는다."),
                (10, "막힌 줄을 다음 주 첫날 맨 위에 적는다. 오늘은 새 주제를 열지 않는다."),
            ]),
        ]
    if practice == "analysis":
        return [
            day(day_title(title, "주장"), [
                (10, opening),
                (20, claim),
                (20, "점화·비용 주장을 기호로 적고 작은 숫자로 참인지 표시한다."),
                (10, "주장을 한 문장으로 줄인다."),
            ]),
            day(day_title(title, "펼치기"), [
                (10, with_focus(f"어제 줄인 '{title}' 주장을 말한다.", claim)),
                (25, trace + " 층을 숫자로 펼치거나 경우를 표로 나눈다. 코드를 작성하지 않는다."),
                (15, "크기를 바꿔 같은 펼치기를 한 번 더 한다."),
                (10, "표가 주장과 어긋나면 표시한다."),
            ]),
            day(day_title(title, "판정"), [
                (10, with_focus(f"어제 '{title}'에서 펼친 표를 말한다.", trace)),
                (40, "오늘 판정 노트를 쓴다. " + code + " 첫 25분은 경우 구분과 결론만 적는다. 이 문장을 코드로 실행하지 않는다. 남은 15분은 숫자 검산이다."),
                (10, "판정 결론을 한 줄로 말한다."),
            ]),
            day(day_title(title, "반례"), [
                (10, with_focus(f"어제 '{title}' 판정 결론을 말한다.", trace)),
                (20, trap),
                (20, "가정을 깨는 입력이나 잘못된 경우 분류를 만들고 어느 줄이 붕괴하는지 적는다."),
                (10, "무엇을 고쳤는지 한 줄로 적는다."),
            ]),
            day(day_title(title, "비용"), [
                (10, with_focus(f"어제 '{title}'에서 고친 한 줄을 말한다.", trap)),
                (20, cost),
                (20, "입력 크기를 키울 때 비용이 어떻게 변하는지 표로 적는다."),
                (10, "그 결론을 한 문장으로 말한다."),
            ]),
            day(day_title(title, "설명"), [
                (10, with_focus(f"어제 적은 '{title}'의 비용 결론을 말한다.", cost)),
                (20, "판정을 가리고 경우 구분과 결론을 다시 쓴다."),
                (20, "왜 맞는지 세 문장으로 적는다."),
                (10, "세 문장을 소리 내어 말한다."),
            ]),
            day(day_title(title, "점검"), [
                (10, with_focus(f"이번 주 '{title}' 주장을 말한다.", claim)),
                (40, check + " 백지에서 판정을 다시 쓰고 숫자 예 하나를 붙인다. 코드를 새로 짜는 것으로 이 칸을 대신하지 않는다."),
                (10, "막힌 줄을 다음 주 첫날 맨 위에 적는다."),
            ]),
        ]
    if practice == "proof":
        return [
            day(day_title(title, "주장"), [
                (10, opening),
                (20, claim),
                (20, "그 주장을 다섯 줄 이하의 예로 참인지 손으로 표시한다."),
                (10, "주장을 한 문장으로 줄인다."),
            ]),
            day(day_title(title, "전개"), [
                (10, with_focus(f"어제 줄인 '{title}' 주장을 말한다.", claim)),
                (25, trace + " 각 문장이 앞 문장에서 나오는지 번호를 붙인다. 문장이 다섯 줄보다 짧으면 예 숫자를 옆에 전개해 한 줄을 더 만든다."),
                (15, "예 숫자를 하나 더 넣어 같은 전개를 다시 한다."),
                (10, "전개가 주장과 어긋나면 그 줄에 표시한다."),
            ]),
            day(day_title(title, "증명"), [
                (10, with_focus(f"어제 '{title}'에서 전개한 예를 말한다.", trace)),
                (40, "오늘 주장을 증명으로 적는다. " + code + " 첫 25분은 가정, 핵심, 결론의 세 단락을 쓴다. 이 문장을 코드로 실행하지 않는다. 남은 15분은 예 숫자를 단락 옆에 넣어 어긋나는 줄을 고친다. 해설은 25분이 지나기 전에는 열지 않는다."),
                (10, "세 단락이 예 숫자와 맞는지 한 줄로 말한다."),
            ]),
            day(day_title(title, "반례"), [
                (10, with_focus(f"어제 '{title}' 증명에서 핵심 문장을 말한다. 예는 다음이다.", trace)),
                (20, trap),
                (20, "그 실패가 생기는 입력을 만들고, 어느 단락이 깨지는지 적는다. 가정을 되돌리면 그 입력이 사라지는지 확인한다."),
                (10, "무엇을 고쳤는지 한 줄로 적는다."),
            ]),
            day(day_title(title, "이유"), [
                (10, with_focus(f"어제 '{title}'에서 고친 한 줄을 말한다. 그 실패는 다음이다.", trap)),
                (20, cost),
                (20, "그 이유를 예 숫자에 대입해 세 줄로 확인한다."),
                (10, "그 결론을 한 문장으로 말한다."),
            ]),
            day(day_title(title, "설명"), [
                (10, with_focus(f"어제 적은 '{title}'의 이유 한 문장을 말한다.", cost)),
                (20, "증명을 가리고 가정, 핵심, 결론을 다시 쓴다."),
                (20, "왜 맞는지 세 문장으로 적는다. 가정, 핵심, 결론 순이다."),
                (10, "세 문장을 소리 내어 말한다."),
            ]),
            day(day_title(title, "점검"), [
                (10, with_focus(f"이번 주 '{title}' 주장을 말한다.", claim)),
                (40, check + " 백지에서 증명을 다시 쓰고 예 하나를 단락 옆에 붙인다. 코드를 새로 짜는 것으로 이 칸을 대신하지 않는다."),
                (10, "막힌 줄을 다음 주 첫날 맨 위에 적는다. 오늘은 새 정리를 열지 않는다."),
            ]),
        ]
    return [
        day(day_title(title, "주장"), [
            (10, opening),
            (20, claim),
            (20, "그 주장을 다섯 줄 이하의 입력에 대해 참인지 손으로 표시한다."),
            (10, "주장을 한 문장으로 줄인다."),
        ]),
        day(day_title(title, "손 추적"), [
            (10, with_focus(f"어제 줄인 '{title}' 주장을 말한다.", claim)),
            (25, trace + " 변수 값을 줄마다 표로 적는다. 표가 짧으면 입력을 바꿔 표를 한 번 더 만든다."),
            (15, "입력을 하나 바꿔 같은 추적을 다시 한다."),
            (10, "추적이 주장과 어긋나면 그 칸에 표시한다."),
        ]),
        day(day_title(title, "구현"), [
            (10, with_focus(f"어제 '{title}'에서 추적한 예를 말한다.", trace)),
            (40, "오늘 예제를 코드로 작성해 실행한다. " + code + " " + (
                "각 출력과 손 추적 표를 나란히 적고, 25분이 지나기 전에는 해설을 보지 않는다."
                if "두 개 더" in code
                else "입력을 바꾼 경우를 두 개 더 같은 코드로 실행하고, 각 출력과 손 추적 표를 나란히 적는다. 25분이 지나기 전에는 해설을 보지 않는다."
            )),
            (10, "방금 추적한 예가 코드와 같은 결과를 내는지 확인한다."),
        ]),
        day(day_title(title, "반례"), [
            (10, with_focus(f"어제 '{title}' 코드를 다음 예로 다시 실행한다.", trace)),
            (20, trap),
            (20, "깨진 입력을 코드에 넣어 보고, 고친 뒤 같은 입력을 다시 넣는다."),
            (10, "무엇을 고쳤는지 한 줄로 적는다."),
        ]),
        day(day_title(title, "시간"), [
            (10, with_focus(f"어제 '{title}'에서 고친 한 줄을 말한다. 그 실패는 다음이다.", trap)),
            (20, cost),
            (20, "입력 크기를 두 배로 하면 연산이 얼마나 늘지 표로 적는다."),
            (10, "그 결론을 한 문장으로 말한다."),
        ]),
        day(day_title(title, "설명"), [
            (10, with_focus(f"어제 적은 '{title}'의 시간 결론을 말한다.", cost)),
            (20, "코드를 가리고 추적 과정을 다시 쓴다."),
            (20, "왜 맞는지 세 문장으로 적는다. 불변, 종료, 결과 순이다."),
            (10, "세 문장을 소리 내어 말한다."),
        ]),
        day(day_title(title, "점검"), [
            (10, with_focus(f"이번 주 '{title}' 주장을 말한다.", claim)),
            (40, check + " 백지에서 코드를 다시 작성하고, 입력을 바꾼 한 경우를 더 실행한다."),
            (10, "막힌 입력을 다음 주 첫날 맨 위에 적는다. 오늘은 새 구조를 열지 않는다."),
        ]),
    ]

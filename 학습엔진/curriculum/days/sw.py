# -*- coding: utf-8 -*-
"""Software architecture & trade-offs (sw) 7-day plan builder."""
from curriculum.common import day, day_title, particle_eul, with_focus


def sw_days(prev, title, rule, case, mistake, work, why, check, prev_line=""):
    if prev == "시작":
        opening = with_focus(
            f"오늘은 '{title}'{particle_eul(title)} 시작한다. 실제 코드나 설계 사례에서 최근 변경 하나를 고르고, 첫 줄 요약과 대상 파일 이름을 적는다. 이번 주 핵심 원칙은 다음과 같다.",
            rule,
        )
    else:
        opening = with_focus(
            f"지난주 '{prev}'의 설계 원칙과 트레이드오프를 노트를 덮고 말한다. 그 기준은 다음과 같다.",
            prev_line,
        )
    return [
        day(day_title(title, "기준과 대조"), [
            (10, opening),
            (20, rule + " 이 원칙을 노트에 적고, 이번 주 사례에 적힌 대비 관점과 나란히 비교한다."),
            (20, "이 원칙을 따랐을 때 얻는 이점과, 기계적으로 적용했을 때 생기는 부작용을 각각 두 줄로 적는다."),
            (10, "핵심 판단 기준을 한 문장으로 요약한다."),
        ]),
        day(day_title(title, "사례 분석"), [
            (10, with_focus(f"어제 '{title}'에서 한 문장으로 요약한 설계 기준을 노트를 덮고 말한다.", rule)),
            (25, case + " 지정된 시나리오의 파일·모듈·장애 지점을 따라가며 분석한다. 분량이 짧으면 대조되는 두 번째 변형을 함께 본다."),
            (15, "원칙이 잘 지켜진 줄과 추상화가 새거나 결합이 꼬인 줄을 구분해 표시한다."),
            (10, "문제가 드러난 파일 이름과 줄을 기록한다."),
        ]),
        day(day_title(title, "설계와 적용"), [
            (10, with_focus(f"어제 '{title}' 사례에서 기준과 어긋난다고 표시한 파일 이름과 그 줄을 말한다. 적용할 기준은 다음과 같다.", rule)),
            (40, work + " 산출물은 두 대안을 비교한 한 페이지 설계 노트 또는 리팩터링 커밋이다. 첫 25분은 두 가지 대안을 스케치하거나 코드를 고치고, 남은 15분은 변경 비용과 인지 부하 기준으로 다듬는다. 기초 문법이나 빌드 도구 설정은 이 시간에 다루지 않는다."),
            (10, "완성한 설계 노트 제목이나 커밋 제목을 한 줄로 적는다."),
        ]),
        day(day_title(title, "반례와 한계"), [
            (10, with_focus(f"어제 '{title}'에서 작성한 설계 노트나 커밋 제목을 한 줄로 말한다. 적용한 기준은 다음과 같다.", rule)),
            (20, mistake),
            (20, "이 원칙을 맹목적으로 적용했을 때 오히려 설계가 나빠지는 반례 시나리오를 만들고, 대안 설계와 다섯 줄로 비교한다."),
            (10, "이 실패 패턴에 짧은 이름을 붙인다."),
        ]),
        day(day_title(title, "트레이드오프 근거"), [
            (10, with_focus(f"어제 '{title}'에서 이름 붙인 실패 패턴을 말한다. 이번 주 기준은 다음과 같다.", rule)),
            (20, why),
            (20, f"어제 만든 '{title}' 산출물의 두 지점에 이 근거를 대입해, 어떤 변경 비용이 줄고 어떤 비용을 감수했는지 적는다."),
            (10, "선택과 거절의 근거를 두 문장으로 줄인다."),
        ]),
        day(day_title(title, "구술 설명"), [
            (10, with_focus(f"어제 정리한 '{title}'의 트레이드오프 근거 두 문장을 말한다. 기준은 다음과 같다.", rule)),
            (20, "노트를 가리고 문제 상황과 두 가지 설계 대안을 백지에 다시 스케치한다."),
            (20, "이번 맥락에서 채택한 원칙과 의도적으로 거절한 원칙을 세 문장으로 적는다."),
            (10, "세 문장을 소리 내어 막힘없이 설명한다."),
        ]),
        day(day_title(title, "점검"), [
            (10, with_focus(f"이번 주 '{title}'의 설계 기준을 한 문장으로 말한다.", rule)),
            (40, check + " 노트를 덮고 새로운 사례 하나에 40분 동안 두 대안을 비교 적용한다. 선택과 거절의 근거가 담긴 설계 노트나 커밋 제목이 남아야 이번 주가 끝난다."),
            (10, "판단이 막혔던 지점 한 줄을 다음 주 첫날 맨 위에 적는다. 오늘은 새로운 주제를 열지 않는다."),
        ]),
    ]
